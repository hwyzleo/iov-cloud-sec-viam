-- SEC-VIAM-DSN-CR-001 V1 Baseline
-- 目标表结构按迁入源实现逐项映射：
--   * 证书登记/操作   ← VMD tb_veh_certificate / tb_veh_certificate_operation
--   * 业务密钥目录     ← VMD tb_device_business_key
--   * 开通批次/item    ← VMD tb_business_key_provisioning / tb_business_key_provisioning_item
--   * KL1 交付租约     ← VMD tb_keyprov_delivery_lease
--   * Outbox          ← VMD tb_vmd_outbox
--   * 安全主体/资产映射、成功接入记录、安全开通状态、准入审计、Inbox 为 VIAM 目标概念
-- 存量迁移状态：未验证（本库为空开发库可直接建目标结构；VMD/TSP 源库存量核实后再记录迁移结论）。
-- 禁止保存明文密钥、完整 Wrapped Key、设备私钥或可恢复密钥材料；响应字节仅存加密 BLOB/受控引用。

